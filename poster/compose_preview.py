#!/usr/bin/env python3
"""Local full-resolution mirror of the Canva A0 layout (design DAHWusBW1Jc), used to check
positions/orientation at print scale. Coordinates are the Canva page coordinates (3179 x 4494 px
= 841 x 1189 mm); everything is rendered at S x scale."""
from PIL import Image, ImageDraw, ImageFont
S = 3
W, H = 3179, 4494
img = Image.new("RGB", (W * S, H * S), "white")
d = ImageDraw.Draw(img)
F = "/usr/share/fonts/liberation/LiberationSans-{}.ttf"
def font(px, bold=False):
    return ImageFont.truetype(F.format("Bold" if bold else "Regular"), int(px * S))
def text(s, x, y, w, px, color, bold=False, lh=1.35):
    f = font(px, bold); words = s.split(); line = ""; yy = y * S
    for wd in words:
        t = (line + " " + wd).strip()
        if d.textlength(t, font=f) > w * S and line:
            d.text((x * S, yy), line, font=f, fill=color); yy += px * lh * S; line = wd
        else:
            line = t
    d.text((x * S, yy), line, font=f, fill=color); yy += px * lh * S
    return yy / S
def place(path, x, y, w, h):
    im = Image.open(path).convert("RGB").resize((w * S, h * S), Image.LANCZOS); img.paste(im, (x * S, y * S))
    return (x, y, w, h)
boxes = []

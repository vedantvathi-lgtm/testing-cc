b = text("Bhuvan B  ·  ACM SIGPLAN-M Mentee | Open Source Contributor  ·  IICT 2026, paper #55", 76, 372, 3027, 56, "#2F2F2F"); boxes.append(("author", 372, b))
b = text("An interval analysis proves runtime-varying WGSL indices in bounds, so wgpu can emit those accesses without clamps: 29 → 0 clamps in 6 synthetic kernels, 118 of 729 real-world accesses proved.", 76, 470, 3027, 52, "#2E9FB0", True, 1.3); boxes.append(("summary", 470, b))
d.rectangle([76 * S, 640 * S, 3103 * S, 645 * S], fill="#0033A0")
P = {"policies": ("pieces/policies_nocaption.png", 76, 690, 788), "pipeline": ("pieces/pipeline.png", 76, 1658, 767), "rules": ("pieces/rules.png", 76, 2465, 1108),
     "coverage": ("assets/coverage.png", 76, 3700, 385), "qa": ("pieces/r4_qa.png", 1100, 690, 1211), "worked": ("pieces/worked_example.png", 1100, 1941, 1466),
     "soundness": ("pieces/soundness.png", 1100, 3447, 808), "v4": ("assets/v4_kernels.png", 2124, 777, 425), "vello": ("assets/vello_realworld.png", 2124, 1447, 655),
     "methods": ("pieces/methods.png", 2124, 2265, 725), "related": ("pieces/related.png", 2124, 3030, 886)}
